ADMIN_SCREENSHOTS = {
    'editor-person-report': 'admin-person-report',
    'editor-account': 'admin-account',
}


def editorial_chapters(role):
    """Возвращает общие предметные главы с предусловиями и снимками целевой роли."""
    if role == 'editor':
        return tuple(EDITOR_CHAPTERS)
    if role != 'admin':
        raise KeyError(role)
    chapters = []
    for item in EDITOR_CHAPTERS:
        scenarios = []
        for scenario in item.scenarios:
            preconditions = ADMIN_PRECONDITIONS.get(scenario.preconditions, scenario.preconditions)
            screenshot = ADMIN_SCREENSHOTS.get(scenario.screenshot, scenario.screenshot)
            if preconditions != scenario.preconditions or screenshot != scenario.screenshot:
                scenario = replace(scenario, preconditions=preconditions, screenshot=screenshot)
            scenarios.append(scenario)
        chapters.append(replace(item, scenarios=tuple(scenarios)))
    return tuple(chapters)


